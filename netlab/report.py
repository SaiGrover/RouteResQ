"""Comparison rows and the Markdown report for the upload-under-link-failure experiment.

The app, ``reports/file_upload_link_failure.md``, the project report and the slides all take
their numbers from these rows, so the same run always shows the same values everywhere.
"""
from __future__ import annotations

from pathlib import Path

from common.paths import PROJECT_ROOT
from netlab.config import RUN_MODES

REPORT_PATH = PROJECT_ROOT / "reports" / "file_upload_link_failure.md"

STALL_DEFINITION = ("Stall duration = the longest interval in which the server's count of received file bytes did "
                    "not increase. In the fault runs only pauses ending after the link went down count; in the "
                    "baseline the whole transfer counts.")
BACKUP_DEFINITION = ("Backup path used = at least 16 KiB more left the client's backup interface while the primary "
                     "link was down (interface byte counters, sampled every 50 ms).")


def na(x, fmt: str = "{}") -> str:
    return "n/a" if x is None else fmt.format(x)


def yes_no(x) -> str:
    return "n/a" if x is None else ("yes" if x else "no")


def rows(run: dict) -> list[dict]:
    """One comparison row per mode, values as measured (None = not measurable in that run)."""
    out = []
    for mode in RUN_MODES:
        r = run["runs"].get(mode)
        if not r:
            continue
        o = r["outcome"]
        first_bk = (round(o["first_backup_traffic_t"] - o["link_down_t"], 3)
                    if o.get("first_backup_traffic_t") is not None and o.get("link_down_t") is not None else None)
        out.append({
            "mode": mode, "run": r["label"], "outcome": o["label"], "code": o["code"],
            "completed": o["completed"], "total_s": o["total_s"], "stall_s": o["stall_s"],
            "retry_required": o["retry_required"], "connections": o["connections"],
            "same_connection": o["same_connection"], "backup_used": o["backup_used"], "backup_bytes": o["backup_bytes"],
            "first_backup_after_down_s": first_bk, "resumed_after_link_up_s": o.get("resumed_after_link_up_s"),
            "fault_at_pct": (round(o["fault_at_bytes"] / r["file"]["size"] * 100, 1) if o.get("fault_at_bytes") else None),
            "sha256_match": o["sha256_match"], "summary": r["summary"],
        })
    return out


def source_line(run: dict) -> str:
    m = run["meta"]
    if m.get("source") == "recorded":
        return (f"Recorded run: captured locally on {m.get('started', '?')[:10]} with the {m.get('backend')} backend "
                f"(real TCP upload in an isolated Linux test network) and replayed here from saved data.")
    return f"Live run {m.get('run_id')}: {m.get('backend')} backend, started {m.get('started')}."


def write_report(run: dict, path: Path = REPORT_PATH) -> Path:
    cfg = run["meta"]["config"]
    f = next(iter(run["runs"].values()))["file"]
    lines = [
        "# File upload under link failure",
        "",
        "_Generated by RouteResQ (`python -m netlab.runner --report`) from the stored run data._",
        "",
        "**Question.** If a network link goes down halfway through a file upload, does the upload continue on a "
        "backup route, stall until the link returns, or fail and need a retry?",
        "",
        f"**Source.** {source_line(run)}",
        "",
        "## Set-up",
        "",
        "```",
        "                primary link (direct, 5 ms each way)",
        "   client cp0 --------------------------------- sp0 server",
        "10.98.0.1 cb0 --- rc0 [router] rs0 --- sb0          10.99.0.1",
        "            backup path (two hops, 10 ms each way per hop)",
        "```",
        "",
        "* Three Linux network namespaces joined by veth links, built inside the lab container; the host's "
        "network is not touched. The TCP connection runs between the two service addresses, so it can survive a "
        "change of path.",
        "* The client uploads the real file bytes with RouteResQ's framing (FILE_META, FILE_CHUNK, FILE_END) and "
        "the server replies with its SHA-256. The client is paced so the upload is still running at the fault.",
        f"* File: `{f['name']}`, {f['size']:,} bytes, SHA-256 `{f['sha256'][:16]}...`. Pacing {cfg['rate_kib_s']:g} "
        f"KiB/s in {cfg['chunk_kib']} KiB chunks; socket timeout {cfg['timeout_s']:g} s; up to {cfg['retries']} "
        f"retry (a new TCP connection that re-sends from byte 0; resuming from an offset is not supported).",
        f"* Fault: both ends of the primary link are taken down once the **server** has received "
        f"{cfg['fault_at_pct']:g}% of the file, and brought back {cfg['outage_s']:g} s later.",
        "",
        "| Run | What differs |",
        "|---|---|",
    ]
    for mode in RUN_MODES:
        if mode in run["runs"]:
            lines.append(f"| {run['runs'][mode]['label']} | {run['runs'][mode]['description']} |")
    lines += ["", "No routing protocol runs in the test network. The backup route in the failover run is a "
              "pre-installed floating static route (controlled failover), not distance-vector routing.", "",
              "## Results", "",
              "| Run | Outcome | Total time | Stall | Retry | Same TCP connection | Backup path used | SHA-256 |",
              "|---|---|---|---|---|---|---|---|"]
    for r in rows(run):
        lines.append(f"| {r['run']} | {r['outcome']} | {na(r['total_s'], '{:.2f} s')} | {na(r['stall_s'], '{:.3f} s')} | "
                     f"{yes_no(r['retry_required'])} | {yes_no(r['same_connection'])} | "
                     f"{yes_no(r['backup_used'])} ({na(r['backup_bytes'], '{:,} B')}) | "
                     f"{'match' if r['sha256_match'] else na(r['sha256_match'])} |")
    lines += ["", f"_{STALL_DEFINITION}_", "", f"_{BACKUP_DEFINITION}_", ""]
    for mode, r in run["runs"].items():
        lines += [f"### {r['label']}", "", r["summary"], ""]
        lines += ["| t (s) | Event |", "|---|---|"]
        for ev in r["events"]:
            if ev["kind"] in ("transfer_start", "link_down", "first_backup_traffic", "link_up", "progress_resumed",
                              "server_complete", "client_failed", "retry_started", "server_timeout", "run_limit"):
                lines.append(f"| {ev['t']:.3f} | {ev['kind']}: {ev['detail']} |")
        lines.append("")
        if r.get("routes"):
            lines += ["Forwarding decision on the client (`ip route get 10.99.0.1 from 10.98.0.1`):", ""]
            for x in r["routes"]:
                lines.append(f"* {x['label']}: `{x['c']}`")
            lines.append("")
    lines += ["## Limits", "",
              "* The test network is three namespaces on one Linux kernel with emulated delays; it shows TCP and "
              "kernel forwarding behaviour, not the timing of a real WAN.",
              "* Failover is a floating static route that the kernel uses as soon as the primary interface goes "
              "down. A routing protocol (OSPF, RIP) would add its own detection and convergence time.",
              "* A retry re-sends the whole file; the client cannot resume from a byte offset.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
