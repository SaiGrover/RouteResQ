"""Generate the report's upload-under-link-failure numbers, chart data and table from the stored run.

    python report/make_upload_assets.py        # writes report/routeresq_assets/upload_results.tex

Every number about this experiment in the report is a macro defined here, read from
results/netlab/recorded, so the report always matches the app and the slides.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from netlab.report import rows  # noqa: E402
from netlab.runner import recorded_run  # noqa: E402

OUT = Path(__file__).resolve().parent / "routeresq_assets" / "upload_results.tex"


def f(x, nd=2):
    return "n/a" if x is None else f"{x:.{nd}f}"


def main() -> int:
    run = recorded_run()
    if not run:
        raise SystemExit("results/netlab/recorded is missing - run: python -m netlab.runner --record")
    r = {x["mode"]: x for x in rows(run)}
    res = run["runs"]
    cfg = run["meta"]["config"]
    size = run["meta"]["file"]["size"]
    fo, so = res["failover"]["outcome"], res["static"]["outcome"]
    macros = {
        "upFileMiB": f"{size / 1048576:.0f}",
        "upFaultPct": f"{cfg['fault_at_pct']:.0f}",
        "upOutage": f"{cfg['outage_s']:g}",
        "upRate": f"{cfg['rate_kib_s']:.0f}",
        "upTimeout": f"{cfg['timeout_s']:g}",
        "upRetries": f"{cfg['retries']}",
        "upDate": run["meta"]["started"][:10],
        "upKernel": res["baseline"]["environment"]["kernel"].replace("_", r"\_"),
        "upBaseTotal": f(r["baseline"]["total_s"]),
        "upBaseStall": f(r["baseline"]["stall_s"], 3),
        "upFailTotal": f(r["failover"]["total_s"]),
        "upFailStall": f(r["failover"]["stall_s"], 3),
        "upFailFirstBackup": f(r["failover"]["first_backup_after_down_s"], 3),
        "upFailBackupMiB": f(r["failover"]["backup_bytes"] / 1048576),
        "upFailBackupBytes": f"{r['failover']['backup_bytes']:,}",
        "upStatTotal": f(r["static"]["total_s"]),
        "upStatStall": f(r["static"]["stall_s"]),
        "upStatResume": f(r["static"]["resumed_after_link_up_s"]),
        "upStatBackupBytes": f"{r['static']['backup_bytes']:,}",
        "upBaseBackupBytes": f"{r['baseline']['backup_bytes']:,}",
        "upDownT": f(fo["link_down_t"]),
        "upUpT": f(fo["link_up_t"]),
    }
    lines = ["% generated by report/make_upload_assets.py from results/netlab/recorded - do not edit by hand"]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in macros.items()]

    # progress chart coordinates (receiver-confirmed %), thinned to keep the PDF small
    def coords(mode: str) -> str:
        pts = [(t, b) for t, b, c in res[mode]["progress"] if c == 1]
        keep, last_t = [], -1.0
        for i, (t, b) in enumerate(pts):
            if t - last_t >= 0.04 or i == len(pts) - 1 or (i + 1 < len(pts) and pts[i + 1][0] - t > 0.3):
                keep.append((t, b))
                last_t = t
        return " ".join(f"({t:.3f},{b / size * 100:.2f})" for t, b in keep)

    for mode, name in (("baseline", "upCoordsBase"), ("failover", "upCoordsFail"), ("static", "upCoordsStat")):
        lines.append(rf"\newcommand{{\{name}}}{{{coords(mode)}}}")

    def yn(x):
        return "n/a" if x is None else ("yes" if x else "no")

    table = []
    for x in rows(run):
        table.append(f"{x['run']} & {x['outcome']} & {f(x['total_s'])} & {f(x['stall_s'], 3)} & "
                     f"{yn(x['retry_required'])} & {yn(x['same_connection'])} & "
                     f"{yn(x['backup_used'])} ({x['backup_bytes']:,} B) & "
                     f"{'match' if x['sha256_match'] else yn(x['sha256_match'])}\\\\")
    lines.append(r"\newcommand{\upTableRows}{" + "\n".join(table) + "}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
